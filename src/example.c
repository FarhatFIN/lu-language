/* ── Chan grow ── */
static void lu_chan_grow(lu_chan_t *c) {
    int newcap = c->cap * 2;
    void **grown = realloc(c->buf, sizeof(void*) * newcap);
    if (!grown) { fprintf(stderr, "[Lu MEM] out of memory\n"); exit(ERR_MEM); }
    c->buf = grown;
    c->cap = newcap;
}
/* safe chan_send with auto-grow */
static void lu_chan_send_safe(lu_chan_t *c, void *v) {
    if (!c) return;
    if (c->tail - c->head >= c->cap) lu_chan_grow(c);
    c->buf[c->tail % c->cap] = v;
    c->tail++;
}



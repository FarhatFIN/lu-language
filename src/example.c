static double lu_pow_num(double base, int64_t exp) {
    double result = 1.0;
    bool neg = exp < 0;
    uint64_t e = neg ? (uint64_t)(-exp) : (uint64_t)exp;
    while (e) {
        if (e & 1u) result *= base;
        base *= base;
        e >>= 1u;
    }
    return neg ? 1.0 / result : result;
}

